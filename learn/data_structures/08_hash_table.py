"""
08. Hash Table: Maps keys to values using a hash function.
Python's built-in dictionary is a highly optimized hash table implementation.
"""

hash_table = {}
hash_table["name"] = "Alice"
hash_table["age"] = 30
hash_table["city"] = "New York"

print(f"Hash Table (Dictionary): {hash_table}")
print(f"Accessing 'name': {hash_table['name']}")
