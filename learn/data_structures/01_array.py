"""
01. Array/List: Basic contiguous memory collection.
In Python, lists are dynamic arrays that can store items of different types.
"""

my_list = [10, 20, 30, 40, 50]
print(f"Original list: {my_list}")
my_list.append(60)
print(f"After appending 60: {my_list}")
print(f"Accessing element at index 2: {my_list[2]}")
